'use strict';
/* Fleet rules in one JSON document (the caller loads and saves it; path is the caller's). Each rule: id, group,
   short title + one-line description, source, on/off, and its text: `claudeMd` ({ at, text }: one bullet line of the
   managed CLAUDE.md) and/or `prompt` ([{ at, join, text }]: blocks of the rule text every agent prompt carries).
   The hub writes the managed CLAUDE.md and the prompt rule text from it; a rule that is off is left out of both.
   Behaviour rules (`code: true`) also switch a hub code path (the server asks on(doc, id)).
   Hand edits of the managed CLAUDE.md are not lost: adopt() takes them into the document on the next check.
   Document: { version, about, claudeMdHead, groups?: [[id, label]...], rules: [...] }. Pure logic. */
const fs = require('fs');

const GROUPS = [['safety', 'Safety'], ['workflow', 'Workflow'], ['timing', 'Timing'], ['hub', 'Hub']];
const MD_NOTE = '<!-- GENERATED by Control Room from its rules file (the Rules tab). A rule turned off there is left out here. ' +
  'A line edited or added here by hand is taken into the rules file on the next check. -->';
const groupsOf = doc => (doc && Array.isArray(doc.groups) && doc.groups.length ? doc.groups : GROUPS);

const load = f => { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch { return null; } };
const save = (f, doc) => { const tmp = f + '.tmp'; fs.writeFileSync(tmp, JSON.stringify(doc, null, 1) + '\n'); fs.renameSync(tmp, f); };
const byId = (doc, id) => ((doc && doc.rules) || []).find(r => r.id === id) || null;
/** A rule is on unless the document says off; no document or an unknown id = on (never drop a rule by accident). */
const on = (doc, id) => { const r = byId(doc, id); return !r || r.on !== false; };

/** The managed CLAUDE.md: the head, the generated note, then every on rule's line in `at` order. */
function renderClaudeMd(doc) {
  const lines = doc.rules.filter(r => r.on !== false && r.claudeMd).sort((a, b) => a.claudeMd.at - b.claudeMd.at).map(r => r.claudeMd.text);
  return `${doc.claudeMdHead}\n${MD_NOTE}\n\n${lines.join('\n')}\n`;
}
/** The rule part of every agent prompt: on blocks in `at` order, each after its own separator ('\n' = same
    paragraph). {{name}} placeholders are filled from vars; unknown ones stay as they are. */
function renderPrompt(doc, vars = {}) {
  const segs = [];
  for (const r of doc.rules) if (r.on !== false) for (const s of r.prompt || []) segs.push(s);
  segs.sort((a, b) => a.at - b.at);
  const txt = segs.map((s, i) => (i ? s.join : '') + s.text).join('');
  return txt.replace(/\{\{(\w+)\}\}/g, (m, k) => vars[k] != null ? String(vars[k]) : m);
}

/** Who toggled. sess = the hub session record ({ user, test: <agent id> } for a test session), ip = the client IP.
    -> { by, via, test }: by is the changelog author (the agent for a test), via names the session in plain words, so
    a test toggle is never reported as the owner's decision. */
function provenance(sess, user, ip) {
  if (sess && sess.test) return { by: String(sess.test), via: `testsession of ${sess.test} (TEST, not the owner)`, test: true };
  return { by: 'u-' + ((user && user.id) || 'owner'), via: `${user && user.admin ? 'owner' : (user && user.name) || 'user'} browser${ip ? ' (' + ip + ')' : ''}`, test: false };
}
/** Turn a rule on or off. prov = provenance() (a plain string = by). Every change goes on the rule's history.
    Returns { rule, changed } (changed false when it already was so); throws on an unknown id. */
function toggle(doc, id, value, prov, t) {
  const r = byId(doc, id);
  if (!r) throw new Error('no rule ' + id);
  const p = typeof prov === 'string' ? { by: prov, via: prov, test: false } : prov;
  const v = !!value, was = r.on !== false;
  if (was === v) return { rule: r, changed: false };
  r.on = v; r.changedAt = t; r.changedBy = p.by; r.changedVia = p.via; r.changedTest = !!p.test;
  r.history = [...(r.history || []), { at: t, on: v, by: p.by, via: p.via, ...(p.test ? { test: true } : {}) }].slice(-50);
  return { rule: r, changed: true };
}
/** Where a rule reaches, in one line (changelog and FYI). */
const reach = x => [x.claudeMd ? 'CLAUDE.md' : '', (x.prompt || []).length ? 'agent prompts' : '', x.code ? 'hub code: ' + (x.codeWhat || x.id) : ''].filter(Boolean).join(', ');
/** The changelog entry for a toggle: a test is titled TEST and logged under the agent, never as the owner. */
function changeEntry(x, v, p) {
  const who = p.test ? `a test (${p.via})` : `the owner (${p.via})`;
  return { by: p.by, entry: { title: `${p.test ? 'TEST: ' : ''}Rule turned ${v ? 'on' : 'off'}: ${x.title} [${x.id}]`, kind: 'change',
    what: `rules ${x.id}: ${v ? 'on' : 'off'} (${reach(x)}). Text rules reach an agent at its next start (CLAUDE.md and the prompt are read then); hub code switches at once. By: ${p.via}.`,
    why: `${who} ${v ? 'turned it on' : 'turned it off'} in the Rules tab`, revert: `Rules tab: tick "${x.title}" ${v ? 'off' : 'on'} again` } };
}
/** The one-line FYI to brain; names the session, and a test says so first so nobody relays it as a decision. */
function fyiLine(x, v, p, clId) {
  if (p.test) return `FYI: TEST toggle, NOT the owner: ${p.via} turned the fleet rule "${x.id}" (${x.title}) ${v ? 'ON' : 'OFF'} (${clId}). Do not relay it as a decision.`;
  return `FYI: the owner turned the fleet rule "${x.id}" (${x.title}) ${v ? 'ON' : 'OFF'} in the Rules tab (${clId}; session: ${p.via}). ${v ? '' : 'Do not re-enable it without asking. '}Reaches: ${reach(x)}.`;
}

/** The bullet lines of a CLAUDE.md text ("- ..." lines, indented continuation lines folded in). */
function bullets(txt) {
  const out = [];
  for (const l of String(txt || '').split('\n')) {
    if (/^- /.test(l)) out.push(l);
    else if (out.length && /^\s+\S/.test(l)) out[out.length - 1] += '\n' + l;
  }
  return out;
}
/** Hand edits of the managed file since the hub last wrote it (fileTxt != renderClaudeMd(doc)):
    a new line -> a new rule (group = the second group, normally 'workflow', on); a changed line -> that rule's text
    (matched by its first 40 chars); an on rule's line that is gone -> the rule turns off.
    Returns { added, edited, off } (rule ids); doc is changed in place. */
function adopt(doc, fileTxt, t) {
  const got = bullets(fileTxt), have = new Set(got), res = { added: [], edited: [], off: [] };
  const known = new Map(doc.rules.filter(r => r.claudeMd).map(r => [r.claudeMd.text, r]));
  const missing = doc.rules.filter(r => r.on !== false && r.claudeMd && !have.has(r.claudeMd.text));
  const key = s => s.slice(0, 40);
  const gs = groupsOf(doc), newGroup = (gs[1] || gs[0])[0];
  let at = 0;
  for (const line of got) {
    const r = known.get(line);
    if (r) { at = r.claudeMd.at; continue; }
    const ed = missing.find(m => key(m.claudeMd.text) === key(line));
    if (ed) { ed.claudeMd.old = ed.claudeMd.text; ed.claudeMd.text = line; ed.changedAt = t; ed.changedBy = 'hand edit of CLAUDE.md'; missing.splice(missing.indexOf(ed), 1); res.edited.push(ed.id); at = ed.claudeMd.at; continue; }
    at += 0.5;   // lands right after the line above it
    const id = 'md-' + t.toString(36) + '-' + res.added.length;
    doc.rules.push({ id, group: newGroup, title: line.replace(/^- /, '').replace(/\s+/g, ' ').slice(0, 70), desc: 'Added to CLAUDE.md by hand; no title written yet.',
      source: 'CLAUDE.md by hand ' + new Date(t).toISOString().slice(0, 10), on: true, adopted: t, claudeMd: { at, text: line } });
    res.added.push(id);
  }
  for (const m of missing) { m.on = false; m.changedAt = t; m.changedBy = 'removed by hand from CLAUDE.md'; res.off.push(m.id); }
  return res;
}

/** What the Rules tab shows: groups in order, each rule without its long text unless full. */
function view(doc, full) {
  return groupsOf(doc).map(([id, label]) => ({ id, label, rules: doc.rules.filter(r => r.group === id).map(r => ({
    id: r.id, title: r.title, desc: r.desc, source: r.source, on: r.on !== false, code: !!r.code, confirm: !!r.confirm, risk: r.risk || '',
    where: [r.claudeMd ? 'CLAUDE.md' : '', (r.prompt || []).length ? 'agent prompt' : '', r.code ? 'hub code' : ''].filter(Boolean),
    changedAt: r.changedAt || null, changedBy: r.changedBy || null, changedVia: r.changedVia || null, changedTest: !!r.changedTest, history: (r.history || []).slice(-10), adopted: !!r.adopted,
    ...(full ? { text: [r.claudeMd ? r.claudeMd.text : '', ...(r.prompt || []).map(s => s.text)].filter(Boolean).join('\n\n'), codeWhat: r.codeWhat || '' } : {}) })) }));
}
module.exports = { GROUPS, MD_NOTE, groupsOf, load, save, byId, on, renderClaudeMd, renderPrompt, provenance, toggle, reach, changeEntry, fyiLine, bullets, adopt, view };
